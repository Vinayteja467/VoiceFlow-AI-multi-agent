import { formatMs, formatScore } from './format';
import type { Run } from '../types';

/** Render a completed run as a portable Markdown document (Export .md). */
export function runToMarkdown(run: Run): string {
  const lines: string[] = [];

  lines.push(`# ${run.title}`, '');
  lines.push(`> Request (${run.source}): ${run.transcript}`, '');
  lines.push(
    `- Status: **${run.status}**`,
    `- Duration: ${formatMs(run.durationMs)}`,
    `- Started: ${new Date(run.createdAt).toLocaleString()}`,
    '',
  );

  if (run.memories.length > 0) {
    lines.push('## Retrieved memory', '');
    for (const m of run.memories) {
      lines.push(`- **${m.type}** (score ${formatScore(m.score)}): ${m.text}`);
    }
    lines.push('');
  }

  if (run.findings && run.findings.length > 0) {
    lines.push('## Research findings', '');
    run.findings.forEach((f, i) => {
      lines.push(`${i + 1}. **${f.title}** — ${f.summary} _(${f.source}, ${f.date})_`);
    });
    lines.push('');
  }

  if (run.plan) {
    lines.push('## Plan', '', run.plan.rationale, '');
    if (run.plan.comparison.length > 0) {
      lines.push('### Options compared', '');
      for (const row of run.plan.comparison) {
        lines.push(`- **${row.option}** → ${row.verdict}`);
        if (row.pros.length) lines.push(`  - Pros: ${row.pros.join('; ')}`);
        if (row.cons.length) lines.push(`  - Cons: ${row.cons.join('; ')}`);
      }
      lines.push('');
    }
    if (run.plan.weekPlan.length > 0) {
      lines.push('### Week plan', '');
      for (const block of run.plan.weekPlan) {
        lines.push(`- \`${block.priority}\` **${block.day} — ${block.block}**: ${block.rationale}`);
      }
      lines.push('');
    }
  }

  if (run.taskOutput && run.taskOutput.tasks.length > 0) {
    lines.push('## Tasks', '');
    for (const t of run.taskOutput.tasks) {
      lines.push(`- [ ] \`${t.priority}\` **${t.title}** — due ${t.due} (owner: ${t.owner})`);
    }
    lines.push('');
    if (run.taskOutput.externalActions.length > 0) {
      lines.push('## Pending approvals (not executed)', '');
      for (const a of run.taskOutput.externalActions) {
        lines.push(`- **${a.actionType}** ${a.title} — ${a.description}`);
      }
      lines.push('');
    }
  }

  if (run.finalResponse) {
    const fr = run.finalResponse;
    lines.push('## Final response', '', `### ${fr.headline}`, '');
    if (fr.keyFindings.length) {
      lines.push('**Key findings**', '');
      fr.keyFindings.forEach((k) => lines.push(`- ${k}`));
      lines.push('');
    }
    if (fr.plan) lines.push('**Plan**', '', fr.plan, '');
    if (fr.nextActions.length) {
      lines.push('**Next actions**', '');
      fr.nextActions.forEach((a) => lines.push(`- [ ] ${a}`));
      lines.push('');
    }
    if (fr.suggestedFollowUps.length) {
      lines.push('**Suggested follow-ups**', '');
      fr.suggestedFollowUps.forEach((s) => lines.push(`- ${s}`));
      lines.push('');
    }
  }

  lines.push('---', '_Generated by VoiceFlow AI._');
  return lines.join('\n');
}
